"""Advanced SubStation Alpha (ASS) script generation for burned-in captions.

Pure text generation, no I/O. The script's ``PlayRes`` equals the export canvas, so every
size in it is in canvas pixels and libass renders it 1:1 on the final frame.

Word highlight is done with one ``Dialogue`` event per spoken word (the whole line is
visible, the active word is recoloured), not with ``\\k`` karaoke, so it looks the same in
every libass build. Events of a line tile ``[line.start, line.end)`` without gaps or
overlaps.
"""

from __future__ import annotations

import re
from typing import Optional, Sequence

from ..core.captions import CaptionLine, CaptionStyle

_ALIGNMENT = {"bottom": 2, "middle": 5, "top": 8}
_MAX_ROWS = 2
_POP_MS = 120
_BOX_COLOUR = "&H78000000"          # black, alpha 0x78 = ~47 % transparent
_MIN_EVENT = 0.005


# ----------------------------------------------------------------------------- helpers
def _rgb(colour: str, default: str = "FFFFFF") -> tuple[str, str, str]:
    c = (colour or "").strip().lstrip("#")
    if len(c) == 3 and re.fullmatch(r"[0-9a-fA-F]{3}", c):
        c = "".join(ch * 2 for ch in c)
    if not re.fullmatch(r"[0-9a-fA-F]{6}", c):
        c = default
    return c[0:2].upper(), c[2:4].upper(), c[4:6].upper()


def ass_colour(colour: str, alpha: int = 0) -> str:
    """``"#RRGGBB"`` -> ASS style colour ``&HAABBGGRR`` (``alpha`` 0 = opaque .. 255)."""
    r, g, b = _rgb(colour)
    return f"&H{max(0, min(255, alpha)):02X}{b}{g}{r}"


def ass_tag_colour(colour: str) -> str:
    """``"#RRGGBB"`` -> the form used inside override tags: ``&HBBGGRR&``."""
    r, g, b = _rgb(colour)
    return f"&H{b}{g}{r}&"


def format_time(seconds: float) -> str:
    """``H:MM:SS.cc`` (centiseconds, the ASS time format)."""
    return _cs_to_time(int(round(max(0.0, seconds) * 100)))


def _cs_to_time(cs: int) -> str:
    h, rem = divmod(cs, 360000)
    m, rem = divmod(rem, 6000)
    s, c = divmod(rem, 100)
    return f"{h}:{m:02d}:{s:02d}.{c:02d}"


def escape_text(text: str) -> str:
    """Make plain text safe inside a Dialogue text field: braces would open an override
    block, a backslash could form ``\\N`` / ``\\h`` / ``\\{``, newlines would end the event."""
    text = re.sub(r"\s*[\r\n]+\s*", " ", text or "")
    text = text.replace("\\", "∖")          # SET MINUS: looks like a backslash, inert
    return text.replace("{", "\\{").replace("}", "\\}")


def _style_name_safe(name: str) -> str:
    return re.sub(r"[,\r\n]", " ", name or "").strip() or "Segoe UI"


def _split_rows(texts: Sequence[str], max_chars: int) -> int:
    """Index of the first token of row 2, or ``len(texts)`` when everything fits one row.
    Rows are balanced (the split minimising the longer row); at most two rows."""
    n = len(texts)
    if n < 2:
        return n
    lens = [len(t) for t in texts]
    total = sum(lens) + (n - 1)
    if total <= max_chars:
        return n
    best, best_cost = n, None
    for k in range(1, n):
        a = sum(lens[:k]) + (k - 1)
        b = sum(lens[k:]) + (n - k - 1)
        cost = max(a, b)
        if best_cost is None or cost < best_cost:
            best, best_cost = k, cost
    return best


def _max_chars(style: CaptionStyle, width: int, size: float) -> int:
    factor = 0.58 * (1.14 if style.uppercase else 1.0)
    return max(6, int(0.9 * width / max(1.0, size * factor)))


# ------------------------------------------------------------------------------ script
def build_ass(lines: Sequence[CaptionLine], style: CaptionStyle, width: int, height: int) -> str:
    """A complete ASS script for ``lines`` (times in seconds, relative to the output's
    start) in ``width`` x ``height`` canvas pixels."""
    width, height = max(2, int(width)), max(2, int(height))
    size = max(4.0, style.size_pct / 100.0 * height)
    outline = max(0.0, style.outline_pct / 100.0 * height)
    align = _ALIGNMENT.get(style.position, 2)
    margin_v = int(round(style.margin_pct / 100.0 * height)) if align != 5 else 0
    margin_h = int(round(0.05 * width))
    primary = ass_colour(style.primary)
    if style.box:
        border_style, border_colour, back_colour = 3, _BOX_COLOUR, _BOX_COLOUR
        outline_px = max(outline, size * 0.22)           # box padding
    else:
        border_style, border_colour = 1, ass_colour(style.outline)
        back_colour = "&H64000000"
        outline_px = outline
    font = _style_name_safe(style.font)

    out = [
        "[Script Info]",
        "; Generated by ClipForge",
        "ScriptType: v4.00+",
        f"PlayResX: {width}",
        f"PlayResY: {height}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: None",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
        "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        f"Style: Caption,{font},{size:.2f},{primary},{primary},{border_colour},{back_colour},"
        f"0,0,0,0,100,100,0,0,{border_style},{outline_px:.2f},0,{align},{margin_h},{margin_h},"
        f"{margin_v},1",
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    max_chars = _max_chars(style, width, size)
    pop = _pop_tag() if style.preset == "pop" else ""
    for line in sorted(lines, key=lambda ln: ln.start):
        out.extend(_line_events(line, style, max_chars, pop))
    return "\r\n".join(out) + "\r\n"


def _pop_tag() -> str:
    return f"{{\\fscx85\\fscy85\\t(0,{_POP_MS},\\fscx100\\fscy100)}}"


def _prep(text: str, style: CaptionStyle) -> str:
    text = re.sub(r"\s+", " ", text or "").strip()
    return text.upper() if style.uppercase else text


def _dialogue(start_cs: int, end_cs: int, body: str) -> str:
    return (f"Dialogue: 0,{_cs_to_time(start_cs)},{_cs_to_time(end_cs)},Caption,,0,0,0,,{body}")


def _line_events(line: CaptionLine, style: CaptionStyle, max_chars: int, pop: str) -> list[str]:
    if line.end - line.start < _MIN_EVENT:
        return []
    l0 = int(round(line.start * 100))
    l1 = max(l0 + 1, int(round(line.end * 100)))

    words = [w for w in line.words if _prep(w.text, style)] if style.highlight_words else []
    if not words:
        body = _rows(_prep(line.text, style).split(" "), max_chars, None, "", "")
        if not body.strip():
            return []
        return [_dialogue(l0, l1, pop + body)]

    texts = [_prep(w.text, style) for w in words]
    # boundaries: first event starts at the line start, each next one at its word's start
    starts: list[int] = []
    for i, w in enumerate(words):
        cs = l0 if i == 0 else int(round(w.start * 100))
        cs = max(cs, starts[-1] if starts else l0)
        starts.append(min(cs, l1))
    hi = ass_tag_colour(style.highlight)
    base = ass_tag_colour(style.primary)
    events: list[str] = []
    for i in range(len(words)):
        s = starts[i]
        e = starts[i + 1] if i + 1 < len(words) else l1
        if e <= s:
            continue
        body = _rows(texts, max_chars, i, hi, base)
        events.append(_dialogue(s, e, (pop if not events else "") + body))
    if events:
        return events
    return [_dialogue(l0, l1, pop + _rows(texts, max_chars, None, hi, base))]


def _rows(texts: Sequence[str], max_chars: int, active: Optional[int], hi: str, base: str) -> str:
    """Escaped text of one event: tokens joined by spaces with at most two rows; token
    ``active`` is wrapped in colour overrides."""
    texts = [t for t in texts if t]
    plain = list(texts)
    brk = _split_rows(plain, max_chars)
    parts: list[str] = []
    for i, t in enumerate(texts):
        esc = escape_text(t)
        if active is not None and i == active:
            esc = f"{{\\c{hi}}}{esc}{{\\c{base}}}"
        if i:
            parts.append("\\N" if i == brk else " ")
        parts.append(esc)
    return "".join(parts)
